#!/usr/bin/env node
/**
 * Regenerates `src/app/core/build-info.ts` with the current build time,
 * right before every `ng build` (see the "build" script in package.json,
 * which chains this in front of it). This is what lets Settings show "am I
 * actually on the latest version" - a calendar-versioned string
 * (`YYYY.MM.DD-HHmm`, UTC) that's bigger/newer by simple string comparison
 * and updates itself automatically on every build, with nothing to
 * remember to bump by hand.
 *
 * Deliberately a plain Node script with no dependencies - it only needs to
 * run once, synchronously, before the Angular CLI starts.
 */
const fs = require('fs');
const path = require('path');

const now = new Date();
const pad = (n) => String(n).padStart(2, '0');
const version = `${now.getUTCFullYear()}.${pad(now.getUTCMonth() + 1)}.${pad(now.getUTCDate())}-${pad(now.getUTCHours())}${pad(now.getUTCMinutes())}`;
const builtAt = now.toISOString();

const outPath = path.join(__dirname, '..', 'src', 'app', 'core', 'build-info.ts');
const contents = `// AUTO-GENERATED by scripts/gen-build-info.js on every \`npm run build\` -
// do not hand-edit, your changes will be overwritten on the next build.
// Committed as a placeholder so the app still compiles before a first
// build has run (e.g. \`ng serve\` during local development).

export const BUILD_INFO = {
  /** Calendar-versioned build id (UTC) - string-comparable, so a newer
   * build is always alphabetically greater than an older one. */
  version: '${version}',
  /** Full ISO timestamp of this build, for a precise "built X ago". */
  builtAt: '${builtAt}',
};
`;

fs.writeFileSync(outPath, contents);
console.log(`Generated ${path.relative(process.cwd(), outPath)} - version ${version}`);
